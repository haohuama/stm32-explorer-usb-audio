# -*- coding: utf-8 -*-
"""add_default_cover.py —— 给「没有单独封面」的曲目加一张默认封面。

背景：`gen_cover.py --song N` 会**整份重写** cover_img.h，跑一次就会把
第 5 首那张照片冲掉。所以这里不重写，而是：
  1) 先把现有头文件里的数组原样读出来（s_cover5 / s_bg5 ...）
  2) 再用给定图片生成 s_coverD / s_bgD（D = default）
  3) 合并写回

用法：
    py Tools/add_default_cover.py "封面.jpg"
之后 lcd_ui.c 里把没有封面的曲目指向 s_coverD / s_bgD 即可。
"""
import argparse
import io
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_cover as G   # noqa: E402
from PIL import Image   # noqa: E402

OUT = G.OUT


def read_arrays(path):
    """把头文件里所有 `static const uint16_t NAME[] = {...}` 读成 dict。"""
    if not os.path.exists(path):
        return {}
    s = io.open(path, encoding="utf-8").read()
    out = {}
    for m in re.finditer(r"static const uint16_t (\w+)\[\] = \{(.*?)\n\};", s, re.S):
        name, body = m.group(1), m.group(2)
        out[name] = [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{4})", body)]
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("image")
    ap.add_argument("--dim", type=float, default=0.55, help="背景板压暗系数")
    ap.add_argument("--blur", type=float, default=8.0)
    a = ap.parse_args()

    old = read_arrays(OUT)
    im = Image.open(a.image)
    cover = G.to565(G.make_cover(im))
    bg = G.to565(G.make_bg(im, a.dim, a.blur))

    # 原有数组全部保留（顺序稳定，避免无谓 diff），新数组排最后
    arrays = dict(old)
    arrays["s_coverD"] = cover
    arrays["s_bgD"] = bg

    with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Auto-generated by Tools/gen_cover.py + add_default_cover.py -- DO NOT EDIT.\n")
        f.write(" * 封面 240x240 / 背景板 400x120（RGB565，屏上 2x 放大）\n")
        f.write(" * s_coverD / s_bgD = 没有单独封面的曲目共用的默认封面（%s）\n"
                % os.path.basename(a.image))
        f.write(" * 像素值 = (r>>3)<<11 | (g>>2)<<5 | (b>>3)\n */\n")
        f.write("#ifndef __COVER_IMG_H\n#define __COVER_IMG_H\n\n#include <stdint.h>\n\n")
        f.write("#define COVER_W   %du\n#define COVER_H   %du\n" % (G.COVER, G.COVER))
        f.write("#define COVER_BG_W %du\n#define COVER_BG_H %du\n\n" % (G.BG_W, G.BG_H))
        for name in sorted(arrays):
            G.emit(f, name, arrays[name])
        f.write("#endif /* __COVER_IMG_H */\n")

    kb = lambda n: len(arrays[n]) * 2 / 1024.0
    print("保留: %s" % ", ".join(sorted(old)))
    print("新增: s_coverD %.1fKB + s_bgD %.1fKB -> %s" % (kb("s_coverD"), kb("s_bgD"), OUT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
