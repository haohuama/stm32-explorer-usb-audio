#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""生成歌词用的大字号原生点阵（40x40 汉字 + 16x40 ASCII）→ cn_font40.h

背景：原来歌词是拿 16x16 点阵按 2x2 块放大（每颗像素变 4 个），看上去就是马赛克。
     现在直接按 40px 渲染一份原生点阵，屏上 1:1 画，边缘干净得多。

字表按「当前歌词实际用到的字」生成（和 DEMO_LYRICS 一致），
所以换歌词后要重跑本脚本；没被收录的字会退回 16x16 放大（能显示，但会略糊）。

用法: python Tools/gen_big_font.py
"""
import os
import re
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LRC = os.path.join(ROOT, "User/Hardware/LCD/lrc_data.h")
OUT = os.path.join(ROOT, "User/Hardware/LCD/cn_font40.h")

FONT_CN = r"C:/Windows/Fonts/simsun.ttc"
SIZE = 40
CN_W = CN_H = 40
ASC_W, ASC_H = 20, 40          # ASCII 格子 20x40：16 宽太瘦，字母挤在一起不好认
ASC_STRIDE = (ASC_W + 7) // 8  # 每行字节数（20 宽 -> 3 字节）
UI_TEXT = "无歌词播放暂停"


def unescape(s):
    out, i = bytearray(), 0
    while i < len(s):
        ch = s[i]
        if ch == "\\" and i + 1 < len(s):
            n = s[i + 1]
            if n == "x":
                out.append(int(s[i + 2:i + 4], 16)); i += 4; continue
            if n == "n":
                out.append(10); i += 2; continue
            if n == "r":
                out.append(13); i += 2; continue
            out.extend(n.encode("gbk", "replace")); i += 2; continue
        out.extend(ch.encode("gbk", "replace")); i += 1
    return bytes(out).decode("gbk", "replace")


def collect_chars():
    s = open(LRC, encoding="utf-8", errors="ignore").read()
    text = []
    for m in re.finditer(r'static const char (s_title\d|s_artist\d|s_lrc\d)\[\] =\n?(.*?);\n', s, re.S):
        for row in re.findall(r'"(.*)"', m.group(2)):
            text.append(unescape(row))
    text.append(UI_TEXT)
    chars = set()
    for t in text:
        for ch in t:
            if ord(ch) < 0x80:
                continue
            try:
                ch.encode("gbk")
            except UnicodeEncodeError:
                continue
            chars.add(ch)
    return sorted(chars, key=lambda c: c.encode("gbk"))


def render_cn(font, ch):
    """40x40，1bpp，行优先：每行 40 位 = 5 字节，MSB 在最左。"""
    im = Image.new("1", (CN_W, CN_H), 0)
    d = ImageDraw.Draw(im)
    d.text((0, -2), ch, font=font, fill=1)     # -2：把中文的基线稍微上提
    px = im.load()
    rows = []
    for y in range(CN_H):
        bits = bytearray(5)
        for x in range(CN_W):
            if px[x, y]:
                bits[x >> 3] |= (0x80 >> (x & 7))
        rows.extend(bits)
    return rows


def render_ascii(font, ch):
    """20x40 单元格：**按固定字号渲染，只做横向压缩**。

    坑：之前按 bbox 高度缩放，导致 ' 和 , 这种小字形被放大成一根竖条。
    现在垂直方向不缩放（保留字形原本的大小/基线位置），只有当宽度超过 20 时才横向压。
    """
    canvas_h = 48
    im = Image.new("L", (SIZE * 2, canvas_h), 0)
    d = ImageDraw.Draw(im)
    d.text((2, 4), ch, font=font, fill=255)          # 4 = 上边留白，保证升部不被裁

    bbox = im.getbbox()
    if not bbox:
        return [0] * (ASC_H * ASC_STRIDE)

    x0, y0, x1, y1 = bbox
    glyph = im.crop((x0, 4, x1, 4 + ASC_H))          # 水平只取字形，垂直固定 40 行
    w, h = glyph.size
    if w > ASC_W:
        glyph = glyph.resize((ASC_W, h), Image.LANCZOS)
        w = ASC_W

    cell = Image.new("L", (ASC_W, ASC_H), 0)
    cell.paste(glyph, ((ASC_W - w) // 2, 0))

    px = cell.load()
    rows = []
    for y in range(ASC_H):
        bits = 0
        for x in range(ASC_W):
            if px[x, y] > 96:
                bits |= (1 << (ASC_W - 1 - x))       # MSB 在最左
        for k in range(ASC_STRIDE):                  # 高位字节在前
            rows.append((bits >> (8 * (ASC_STRIDE - 1 - k))) & 0xFF)
    return rows


def main():
    for f in (FONT_CN,):
        if not os.path.exists(f):
            print("missing font:", f)
            return 1
    font_cn = ImageFont.truetype(FONT_CN, SIZE)
    font_asc = ImageFont.truetype(r"C:/Windows/Fonts/arial.ttf", 32)

    chars = collect_chars()
    print("汉字 %d 个 -> 40x40 点阵 %.1f KB" % (len(chars), len(chars) * CN_W * CN_H / 8 / 1024.0))

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Auto-generated by Tools/gen_big_font.py -- DO NOT EDIT.\n")
        f.write(" * %d 个汉字 40x40 + 95 个 ASCII 16x40（1bpp，行优先，MSB 在左）\n" % len(chars))
        f.write(" * 只含当前歌词/界面用到的字；缺字时 lcd_ui.c 退回 16x16 放大。\n */\n")
        f.write("#ifndef __CN_FONT40_H\n#define __CN_FONT40_H\n\n#include <stdint.h>\n\n")
        f.write("#define CN40_W %du\n#define CN40_H %du\n" % (CN_W, CN_H))
        f.write("#define ASC40_W %du\n#define ASC40_H %du\n#define ASC40_STRIDE %du\n\n"
                % (ASC_W, ASC_H, ASC_STRIDE))

        f.write("typedef struct { uint16_t gbk; uint8_t bits[%d]; } cn40_t;\n\n" % (CN_W * CN_H // 8))
        f.write("static const cn40_t g_cn40[] = {\n")
        for ch in chars:
            code = ch.encode("gbk")
            key = (code[0] << 8) | code[1]
            rows = render_cn(font_cn, ch)
            f.write("  {0x%04X,{%s}},\n" % (key, ",".join("0x%02X" % b for b in rows)))
        f.write("};\n\n")
        f.write("#define CN40_COUNT ((uint16_t)(sizeof(g_cn40)/sizeof(g_cn40[0])))\n\n")

        f.write("/* ASCII 32..126，20x40，每行 3 字节 */\n")
        f.write("static const uint8_t g_asc40[95][%d] = {\n" % (ASC_H * ASC_STRIDE))
        for code in range(32, 127):
            rows = render_ascii(font_asc, chr(code))
            f.write("  {%s},/*'%s'*/\n" % (",".join("0x%02X" % b for b in rows),
                                           chr(code).replace("\\", "\\\\")))
        f.write("};\n\n#endif\n")

    print("wrote", OUT, "%.1f KB" % (os.path.getsize(OUT) / 1024.0))
    return 0


if __name__ == "__main__":
    sys.exit(main())
