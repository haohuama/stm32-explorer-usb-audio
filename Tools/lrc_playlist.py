#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""把 N 个 .lrc 生成 User/Hardware/LCD/lrc_data.h（播放列表 + 每首歌词）。

产物：
    static const char s_lrc1[];   第 1 首歌词（[mm:ss.xx]GBK 文本）
    static const char s_lrc2[];   第 2 首
    ...
    static const char s_title1[]; 第 1 首标题（取文件名 " - " 前的中文部分，GBK）
    ...

同时把全部歌词行写进 Tools/gen_cn_font.py 的 DEMO_LYRICS，
供 gen_cn_font.py 只渲染用到的汉字。

用法:
    python Tools/lrc_playlist.py "江南 - 林俊杰.lrc" "唯一 - G.E.M.邓紫棋.lrc"
    python Tools/lrc_playlist.py --dry-run a.lrc b.lrc
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "User/Hardware/LCD/lrc_data.h")
GEN = os.path.join(ROOT, "Tools/gen_cn_font.py")
MAX_SONGS = 4          # 与 lcd_ui.c 的 SONG_COUNT 对应

META_WORDS = ("作词", "作曲", "编曲", "制作人", "混音", "母带", "出品", "监制")


def read_text(path):
    raw = open(path, "rb").read()
    for enc in ("utf-8-sig", "utf-8", "gbk", "big5"):
        try:
            return raw.decode(enc)
        except Exception:
            pass
    return raw.decode("utf-8", "ignore")


def parse_lrc(text):
    import json
    out = []
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        if line.startswith("{"):
            try:
                obj = json.loads(line)
            except Exception:
                continue
            t = int(obj.get("t", 0))
            seg = obj.get("c") or []
            txt = "".join(s.get("tx", "") for s in seg if isinstance(s, dict)).strip()
            if not txt or any(w in txt for w in META_WORDS):
                continue
            if ":" in txt or "：" in txt:      # 制作人员行
                continue
            out.append((t, txt))
            continue
        stamps = re.findall(r"\[(\d{1,3}):(\d{1,2})(?:[.:](\d{1,3}))?\]", line)
        if not stamps:
            continue
        body = re.sub(r"\[\d{1,3}:\d{1,2}(?:[.:]\d{1,3})?\]", "", line).strip()
        if not body or any(w in body for w in META_WORDS):
            continue
        if ":" in body or "：" in body:
            continue
        if re.fullmatch(r"(VERSE|CHORUS|HOOK|BRIDGE|OUTRO|INTRO)\s*\d*", body, re.I):
            continue
        for mm, ss, frac in stamps:
            ms = int(mm) * 60000 + int(ss) * 1000
            if frac:
                ms += int(frac.ljust(3, "0")[:3])
            out.append((ms, body))
    out.sort(key=lambda x: x[0])
    return out


def ms_to_lrc(ms):
    m, r = divmod(ms, 60000)
    s, msec = divmod(r, 1000)
    return "%02d:%02d.%02d" % (m, s, msec // 10)


def gbk_escape(txt):
    return "".join("\\x%02X" % b for b in txt.encode("gbk", "replace"))


def song_title(path):
    """从文件名取标题：'江南 - 林俊杰.lrc' -> '江南'（只保留可 GBK 编码的非 ASCII 部分）。"""
    base = os.path.splitext(os.path.basename(path))[0]
    head = base.split(" - ")[0].strip()
    keep = "".join(ch for ch in head if ord(ch) > 0x7F)
    while keep:
        try:
            keep.encode("gbk")
            break
        except UnicodeEncodeError:
            keep = keep[:-1]
    return keep or "歌曲"


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    dry = "--dry-run" in sys.argv
    if not args:
        print(__doc__)
        return 2
    if len(args) > MAX_SONGS:
        print("最多 %d 首（与 lcd_ui.c 的 SONG_COUNT 一致）" % MAX_SONGS)
        return 2

    songs = []
    for p in args:
        lines = parse_lrc(read_text(p))
        if not lines:
            print("解析失败:", p)
            return 3
        songs.append((song_title(p), lines))
        chars = set(ch for _, t in lines for ch in t if ord(ch) > 0x7F)
        print("%s: %d 行, %d 汉字, 末行 %s"
              % (os.path.basename(p), len(lines), len(chars), ms_to_lrc(lines[-1][0])))

    total_chars = set()
    for _, lines in songs:
        for _, t in lines:
            total_chars |= set(ch for ch in t if ord(ch) > 0x7F)
    for title, _ in songs:
        total_chars |= set(ch for ch in title if ord(ch) > 0x7F)
    print("并集汉字 %d 个 -> 16x16 字库 %.1f KB"
          % (len(total_chars), len(total_chars) * 32 / 1024.0))

    if dry:
        return 0

    # ---------- 生成 lrc_data.h ----------
    buf = ["/* Auto-generated by Tools/lrc_playlist.py -- DO NOT EDIT.",
           " * 播放列表歌词数据：每首一个 [mm:ss.xx] + GBK 字节流。",
           " * 中文一律 \\xNN 转义，避免源文件编码歧义。",
           " */",
           "#ifndef __LRC_DATA_H",
           "#define __LRC_DATA_H",
           ""]
    for i, (title, lines) in enumerate(songs, 1):
        buf.append("/* ---- 第 %d 首：%s ---- */" % (i, title))
        buf.append("static const char s_title%d[] = \"%s\";" % (i, gbk_escape(title)))
        buf.append("static const char s_lrc%d[] =" % i)
        body = []
        for ms, t in lines:
            body.append('    "[%s]%s\\n"' % (ms_to_lrc(ms), gbk_escape(t)))
        buf.append("\n".join(body) + ";")
        buf.append("")
    # 补齐：lcd_ui.c 固定引用 s_lrc1/s_lrc2/s_title1/s_title2
    for i in range(len(songs) + 1, MAX_SONGS + 1):
        buf.append("/* ---- 第 %d 首：未使用 ---- */" % i)
        buf.append('static const char s_title%d[] = "";' % i)
        buf.append('static const char s_lrc%d[] = "";' % i)
        buf.append("")
    buf.append("#endif /* __LRC_DATA_H */")
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(buf) + "\n")
    print("已生成", OUT)

    # ---------- 同步 gen_cn_font.py ----------
    all_lines = [t for _, lines in songs for _, t in lines]
    all_lines += [title for title, _ in songs]
    block = "DEMO_LYRICS = [\n" + "".join('    "%s",\n' % s.replace('"', "") for s in all_lines) + "]\n"
    g = open(GEN, encoding="utf-8").read()
    g2 = re.sub(r"DEMO_LYRICS = \[\n(?:.*?\n)*?\]\n", block, g, count=1)
    if g2 == g:
        print("警告: gen_cn_font.py 的 DEMO_LYRICS 未更新")
    else:
        open(GEN, "w", encoding="utf-8", newline="").write(g2)
        print("已同步 gen_cn_font.py DEMO_LYRICS（%d 行）" % len(all_lines))

    print("下一步: py Tools/gen_cn_font.py && py Tools/check_font.py && py Tools/build_check.py --microlib")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
