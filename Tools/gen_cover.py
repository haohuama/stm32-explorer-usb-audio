#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""把一张照片转成 LCD 封面数据（User/Hardware/LCD/cover_img.h）。

产物（第 N 首）：
    s_coverN[240*240]  RGB565 封面，屏上 1:1 画在左上角（0,0)-(239,239）
    s_bgN[400*120]     RGB565 背景板（照片中部横条 -> 强模糊 -> 压暗），
                       屏上按 2x 放大铺满整个 800x240 上半屏，
                       垫在封面后面，让「上半屏是一张图」而不是黑块。

用法:
    python Tools/gen_cover.py "照片.jpg" --song 5
    python Tools/gen_cover.py "照片.jpg" --song 5 --dim 0.5 --blur 8
"""
import argparse
import os

from PIL import Image, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "User/Hardware/LCD/cover_img.h")

COVER = 240          # 封面边长（上半屏高 240）
BG_W, BG_H = 400, 120  # 背景板分辨率（屏上 2x 放大 = 800x240）


def to565(img):
    """RGB -> RGB565 像素值列表（带 ±2 LSB 抖动，避免渐变色带）。"""
    raw = img.convert("RGB").tobytes()
    out = []
    for i in range(0, len(raw), 3):
        d = ((i * 7) & 3) - 2          # 伪随机小抖动，够打散 32 级红/64 级绿的色带
        r = min(255, max(0, raw[i] + d))
        g = min(255, max(0, raw[i + 1] + d))
        b = min(255, max(0, raw[i + 2] + d))
        out.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
    return out


def make_cover(im):
    """居中裁正方形 -> 240x240。"""
    w, h = im.size
    s = min(w, h)
    im = im.crop(((w - s) // 2, (h - s) // 2, (w - s) // 2 + s, (h - s) // 2 + s))
    return im.resize((COVER, COVER), Image.LANCZOS)


def make_bg(im, dim, blur):
    """上半屏环境底：照片中部横条 -> 强模糊 -> 压暗 -> 右侧渐隐到近黑。

    右侧渐隐是为了给白色歌名/时间留对比度（实测直接把模糊图压暗，右半边
    又脏又晃眼，字压不住）。x<240 被封面盖住，保持全亮即可。
    """
    im = im.convert("RGB")
    w, h = im.size
    s = min(w, h)
    im = im.crop(((w - s) // 2, 0, (w - s) // 2 + s, s)).resize((800, 800), Image.LANCZOS)
    im = im.crop((0, (800 - 240) // 2, 800, (800 - 240) // 2 + 240))   # 800x240 横条
    im = im.filter(ImageFilter.GaussianBlur(blur * 2.75))               # 先大半径糊掉细节
    im = im.resize((BG_W, BG_H), Image.BOX).filter(ImageFilter.GaussianBlur(blur * 0.75))
    im = im.resize((800, 240), Image.BILINEAR)

    # 压暗（保色相）
    r, g, b = im.split()
    r = r.point(lambda v: int(v * dim))
    g = g.point(lambda v: int(v * dim))
    b = b.point(lambda v: int(v * dim))
    im = Image.merge("RGB", (r, g, b))

    # 水平渐隐：封面右侧从 1.0 衰减到 0.22，混向近黑（给白色文字让出对比度）
    mask = Image.new("L", (800, 1))
    for x in range(800):
        k = 1.0 if x < COVER else max(0.22, 1.0 - 0.78 * min(1.0, (x - COVER) / 320.0))
        mask.putpixel((x, 0), int(255 * k))
    dark = Image.new("RGB", (800, 240), (10, 10, 12))
    im = Image.composite(im, dark, mask.resize((800, 240)))

    return im.resize((BG_W, BG_H), Image.BOX)


def emit(f, name, data, per_line=12):
    f.write("static const uint16_t %s[] = {\n" % name)
    for i in range(0, len(data), per_line):
        f.write("    " + ",".join("0x%04X" % v for v in data[i:i + per_line]) + ",\n")
    f.write("};\n\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("image")
    ap.add_argument("--song", type=int, required=True, help="第几首（1 起）")
    ap.add_argument("--dim", type=float, default=0.50, help="背景板压暗系数 (0~1)")
    ap.add_argument("--blur", type=float, default=8.0, help="背景板高斯模糊半径")
    args = ap.parse_args()

    im = Image.open(args.image)
    n = args.song
    cover = to565(make_cover(im))
    bg = to565(make_bg(im, args.dim, args.blur))

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Auto-generated by Tools/gen_cover.py -- DO NOT EDIT.\n")
        f.write(" * 第 %d 首封面：源图 %s\n" % (n, os.path.basename(args.image)))
        f.write(" * s_cover%d: %dx%d RGB565，画在 (0,0)-(%d,%d)\n"
                % (n, COVER, COVER, COVER - 1, COVER - 1))
        f.write(" * s_bg%d   : %dx%d RGB565，屏上 2x 放大铺满 800x240 上半屏\n"
                % (n, BG_W, BG_H))
        f.write(" * 像素值 = (r>>3)<<11 | (g>>2)<<5 | (b>>3)\n */\n")
        f.write("#ifndef __COVER_IMG_H\n#define __COVER_IMG_H\n\n#include <stdint.h>\n\n")
        f.write("#define COVER_W   %du\n#define COVER_H   %du\n" % (COVER, COVER))
        f.write("#define COVER_BG_W %du\n#define COVER_BG_H %du\n\n" % (BG_W, BG_H))
        emit(f, "s_cover%d" % n, cover)
        emit(f, "s_bg%d" % n, bg)
        f.write("#endif /* __COVER_IMG_H */\n")

    print("封面 %d: %dx%d (%.1f KB) + 背景板 %dx%d (%.1f KB) -> %s"
          % (n, COVER, COVER, len(cover) * 2 / 1024.0, BG_W, BG_H, len(bg) * 2 / 1024.0, OUT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
