/* ============================================================
 * tp.h —— 4.3" 屏的电阻触摸（XPT2046，SPI 位操作）
 *
 * 引脚取自正点原子探索者官方触摸例程（与本项目已用外设无冲突）：
 *   T_PEN  = PB1  （输入，按下为低）
 *   T_CS   = PC13 （输出）
 *   T_MISO = PB2  （输入）
 *   T_MOSI = PF11 （输出）
 *   T_SCK  = PB0  （输出）
 * 这 5 个脚在本工程里原本都是空闲的，即使触摸没接上也不会影响 LCD/音频/USB。
 *
 * 只做「按下 + 屏幕坐标」两件事，够画三个按钮用；不做手势/校准界面。
 * 校准常数在 tp.c 顶部，若左右/上下反了改 4 个宏即可（串口会把原始值打出来）。
 * ============================================================ */
#ifndef __TP_H
#define __TP_H

#include <stdint.h>

void    tp_init(void);
/* 有按下返回 1，并给出屏幕像素坐标（0..799 / 0..479）；未按返回 0 */
uint8_t tp_scan(uint16_t *x, uint16_t *y);
/* 最近一次原始 ADC 值（排查/校准用） */
void    tp_last_raw(uint16_t *rx, uint16_t *ry);

/* 开机自检/诊断：当前 T_PEN 引脚电平（0=低，1=高）；
 * 空闲时若读到 0，说明 PEN 是「按下为高」或引脚悬空，需要在 tp.c 改有效电平 */
uint8_t tp_pen_level(void);

/* 诊断计数：PEN 检测到按下的次数 / 成功读到坐标 / ADC 无效丢弃。
 * 每 3 秒由主循环打印一次，用来判断是哪一层断了：
 *   pen=0            -> PEN 引脚没接 / 有效电平反了 / 屏不是这块触摸
 *   pen>0, ok=0      -> SPI 位操作没读到数据（MISO/MOSI/SCK/CS 引脚不对）
 *   pen>0, ok>0      -> 驱动正常，只是坐标校准不对（改 tp.c 顶部 4 个宏） */
void tp_stats(uint32_t *pen, uint32_t *ok, uint32_t *bad);

#endif /* __TP_H */
